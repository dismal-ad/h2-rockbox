#include <string.h>
#include "vfile.h"

const struct vfile_ops *vfile_ops = NULL;

void vfile_register(const struct vfile_ops *ops)
{
    vfile_ops = ops;
}

bool vfile_is_path(const char *path)
{
    return vfile_ops && path &&
           !strncmp(path, vfile_ops->prefix, strlen(vfile_ops->prefix));
}
